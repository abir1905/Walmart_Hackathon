// Helper functions
export const getProductsByType = (type) => {
  return Object.values(allProducts)
    .flat()
    .filter(product => product.type === type);
};

export const getAllProductTypes = () => {
  const types = new Set();
  Object.values(allProducts)
    .flat()
    .forEach(product => types.add(product.type));
  return Array.from(types);
};

export const getAllBrands = () => {
  const brands = new Set();
  Object.values(allProducts)
    .flat()
    .forEach(product => brands.add(product.brand));
  return Array.from(brands);
};

// Get brands for a specific product type
export const getBrandsForType = (type) => {
  const brands = new Set();
  Object.values(allProducts)
    .flat()
    .filter(product => product.type === type)
    .forEach(product => brands.add(product.brand));
  return Array.from(brands);
};

// Get products by type and brand
export const getProductsByTypeAndBrand = (type, brand) => {
  return Object.values(allProducts)
    .flat()
    .filter(product => 
      product.type === type && 
      product.brand === brand
    );
};